import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const pages = process.argv.length === 3 && process.argv[2] === '--pages';
const sidebar = process.argv.length === 3 && process.argv[2] === '--sidebar';
const content = process.argv.length === 3 && process.argv[2] === '--content';
const general = process.argv.length === 3 && process.argv[2] === "--general";
const monitor = process.argv.length === 3 && process.argv[2] === '--monitor';
const icons = process.argv.length === 3 && process.argv[2] === '--icons';
const styles = process.argv.length === 3 && process.argv[2] === '--styles';
const appearance = process.argv.length === 3 && process.argv[2] === '--appearance';
const modes = process.argv.length === 3 && process.argv[2] === '--modes';
if (process.argv.length !== 2 && !pages && !sidebar && !modes && !styles && !appearance && !content && !icons && !monitor && !general) throw Error('不加参数检查设置布局；--pages 检查管理页面；--sidebar 检查侧栏布局；--modes 检查模式展示；--styles 检查主题风格；--appearance 检查明暗外观；--content 检查字体和内容宽度；--icons 检查文件图标；--monitor 检查任务监控；--general 检查常规任务、通知与菜单栏。');
const kind = general ? "general-settings" : monitor ? 'task-monitor' : icons ? 'file-icons' : content ? 'content-appearance' : styles ? 'theme-styles' : appearance ? 'appearance' : modes ? 'mode-presentation' : sidebar ? 'sidebar-layout' : pages ? 'settings-pages' : 'settings-layout';
const evidence = path.join(root, 'evidence/agent');
await mkdir(evidence, { recursive: true });
const output = await mkdtemp(path.join(evidence, kind + '-command-'));
await mkdir(path.join(output, 'shared-home'));
const app = process.env.BLUEFATFISH_APP ?? path.join(root, 'build/蓝色大肥鱼.app');
const binary = path.join(app, 'Contents/MacOS/BlueFatFish');
const hash = () => readFile(binary).then(data => createHash('sha256').update(data).digest('hex'));
const binaryHash = await hash();
const result = spawnSync(binary, ['--check', output, '--' + kind + '-check', ...(monitor ? ['--task-monitor-source', path.join(root, 'README.md')] : [])], { encoding: 'utf8', timeout: 60000 });
await writeFile(path.join(output, 'stdout.log'), result.stdout ?? '');
await writeFile(path.join(output, 'stderr.log'), result.stderr ?? '');
await writeFile(path.join(output, 'process.json'), JSON.stringify({ app, binaryHash, appPID: result.pid, exit: result.status, signal: result.signal }, null, 2) + '\n');
if (result.error || result.status !== 0) throw result.error ?? Error(result.stderr || result.stdout);
const report = JSON.parse(await readFile(path.join(output, kind + '-report.json'), 'utf8'));
if (report.appPID !== result.pid || await hash() !== binaryHash) throw Error('Settings check process or application changed');
const success = report.success && report.modelRequests === 0 && Object.values(report.checks).every(Boolean);
console.log(JSON.stringify({ output, binaryHash, appPID: result.pid, success, checks: Object.keys(report.checks).length, failed: Object.keys(report.checks).filter(key => !report.checks[key]), modelRequests: report.modelRequests }));
process.exitCode = success ? 0 : 1;
