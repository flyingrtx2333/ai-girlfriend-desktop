import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const app = process.env.BLUEFATFISH_APP;
if (!app || process.argv.length !== 2) throw Error('请通过 BLUEFATFISH_APP 指定本轮验收应用；此检查不调用模型。');
const evidence = path.join(root, 'evidence/agent');
await mkdir(evidence, { recursive: true });
const output = await mkdtemp(path.join(evidence, 'operation-confirmation-command-'));
await mkdir(path.join(output, 'shared-home'));
const binary = path.join(app, 'Contents/MacOS/BlueFatFish');
const hash = async () => createHash('sha256').update(await readFile(binary)).digest('hex');
const binaryHash = await hash();
const child = spawn(binary, ['--check', output, '--operation-confirmation-check'], { cwd: root, stdio: ['ignore', 'pipe', 'pipe'] });
const completed = new Promise((resolve, reject) => { child.once('error', reject); child.once('exit', resolve); });
let stdout = '', stderr = '';
child.stdout.on('data', data => { stdout += data; });
child.stderr.on('data', data => { stderr += data; });
await writeFile(path.join(output, 'process.json'), JSON.stringify({ app, binaryHash, appPID: child.pid }, null, 2) + '\n');
console.log(JSON.stringify({ output, appPID: child.pid, binaryHash }));
const code = await completed;
await writeFile(path.join(output, 'stdout.log'), stdout);
await writeFile(path.join(output, 'stderr.log'), stderr);
const report = JSON.parse(await readFile(path.join(output, 'operation-confirmation-report.json'), 'utf8'));
const sameBinary = binaryHash === await hash();
const deletion = report.dialogs.find(dialog => dialog.text.includes('永久删除25项任务？'));
const names = new Set((deletion?.text ?? '').split(/\r?\n/).map(value => value.trim()));
const allDeletionNamesPresented = Array.from({ length: 25 }, (_, index) => `取消删除验收-${index + 1}`).every(name => names.has(name));
const success = code === 0 && report.appPID === child.pid && sameBinary && report.success && report.modelRequests === 0 && Object.values(report.checks).every(Boolean) && allDeletionNamesPresented && report.dialogs.length > 0 && report.dialogs.every(dialog => dialog.styled);
const proof = { output, appPID: child.pid, exit: code, binaryHash, sameBinary, success, allDeletionNamesPresented, checks: Object.keys(report.checks).length, failed: Object.keys(report.checks).filter(key => !report.checks[key]), modelRequests: report.modelRequests, error: report.error };
await writeFile(path.join(output, 'process-result.json'), JSON.stringify(proof, null, 2) + '\n');
console.log(JSON.stringify(proof));
process.exitCode = success ? 0 : 1;
