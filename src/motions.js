// Shape-preserving tangents plus quintic Hermite interpolation: continuous speed
// and acceleration, with no ringing across held poses or neutral endpoints.
function tangent(keys, index, column) {
  if (!index || index === keys.length - 1) return 0;
  const a = keys[index - 1], b = keys[index], c = keys[index + 1];
  const h0 = b[0] - a[0], h1 = c[0] - b[0];
  const d0 = ((b[column] ?? 0) - (a[column] ?? 0)) / h0;
  const d1 = ((c[column] ?? 0) - (b[column] ?? 0)) / h1;
  if (d0 * d1 <= 0) return 0;
  const w0 = 2 * h1 + h0, w1 = h1 + 2 * h0;
  return (w0 + w1) / (w0 / d0 + w1 / d1);
}
function sampleTrack(keys, time) {
  const end = keys.length - 1;
  if (time <= keys[0][0]) return [keys[0][1] ?? 0, keys[0][2] ?? 0, keys[0][3] ?? 0];
  if (time >= keys[end][0]) return [keys[end][1] ?? 0, keys[end][2] ?? 0, keys[end][3] ?? 0];
  let i = 0;
  while (keys[i + 1][0] < time) i++;
  const a = keys[i], b = keys[i + 1], span = b[0] - a[0], t = (time - a[0]) / span;
  const t2 = t * t, t3 = t2 * t, t4 = t3 * t, t5 = t4 * t;
  const ease = 10 * t3 - 15 * t4 + 6 * t5;
  const h0 = t - 6 * t3 + 8 * t4 - 3 * t5, h1 = -4 * t3 + 7 * t4 - 3 * t5;
  return [1,2,3].map(column => {
    const start = a[column] ?? 0, delta = (b[column] ?? 0) - start;
    const limit = 2 * Math.abs(delta);
    const clamp = v => Math.max(-limit, Math.min(limit, v));
    return start + delta * ease + clamp(tangent(keys, i, column) * span) * h0 + clamp(tangent(keys, i + 1, column) * span) * h1;
  });
}
export function sampleMotion(name, time = 0) {
  const spec = name === 'startle' ? startle : MOTIONS[name] || COMPANION_MOTIONS[name];
  if (!spec || time < 0 || time >= spec.duration) return null;
  const p = { joints: {}, lift: 0, yaw: 0, blink: !!spec.blink && time > spec.blink[0] && time < spec.blink[1] };
  for (const [joint, keys] of Object.entries(spec.joints)) p.joints[joint] = sampleTrack(keys, time);
  for (const channel of ['balance', 'hands', 'eyes', 'mouth', 'tail', 'emotion', 'body']) if (spec[channel]) p[channel] = sampleTrack(spec[channel], time);
  if (spec.lift) p.lift = sampleTrack(spec.lift, time)[0];
  if (spec.flight) {
    const [takeoff, landing, height] = spec.flight;
    if (time > takeoff && time < landing) {
      const phase = (time - takeoff) / (landing - takeoff);
      p.lift = 4 * height * phase * (1 - phase);
    }
  }
  return p;
}
